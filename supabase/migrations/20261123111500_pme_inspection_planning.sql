create or replace function private.audit_pme_physical_inspection_document()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Une session authentifiée est requise pour gérer les documents physiques.';
  end if;

  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.updated_by := auth.uid();
    new.checked_by := case when new.status = 'ATTENDU' then null else auth.uid() end;
  end if;

  if tg_op = 'UPDATE' then
    if new.pme_id is distinct from old.pme_id then
      raise exception 'Un document physique ne peut pas être déplacé vers une autre PME.';
    end if;
    new.created_by := old.created_by;
    new.created_at := old.created_at;
    new.updated_at := now();
    new.updated_by := auth.uid();
    if new.status is distinct from old.status or new.checked_at is distinct from old.checked_at then
      new.checked_by := case when new.status = 'ATTENDU' then null else auth.uid() end;
    end if;
  end if;

  if tg_when = 'AFTER' and tg_op = 'UPDATE' then
    insert into public.pme_physical_inspection_document_history(
      document_id, pme_id, action, before_data, after_data, actor_id
    ) values (
      new.id, new.pme_id, 'MODIFICATION', to_jsonb(old), to_jsonb(new), auth.uid()
    );
  elsif tg_when = 'AFTER' then
    insert into public.pme_physical_inspection_document_history(
      document_id, pme_id, action, after_data, actor_id
    ) values (new.id, new.pme_id, 'AJOUT', to_jsonb(new), auth.uid());
  end if;
  return new;
end;
$$;
