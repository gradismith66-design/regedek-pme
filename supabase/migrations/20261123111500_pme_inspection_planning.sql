create or replace function private.audit_pme_inspection_appointment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Une session authentifiée est requise pour gérer une inspection.';
  end if;

  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.updated_by := auth.uid();
    if new.inspector_id is distinct from old.inspector_id then
      if not exists (
        select 1 from public.staff_profiles s
        where s.user_id = new.inspector_id and s.role in ('admin', 'agent')
      ) then
        raise exception 'L’inspecteur désigné doit avoir un rôle d’agent ou d’administrateur.';
      end if;
    end if;
  end if;

  if tg_op = 'UPDATE' then
    if new.pme_id is distinct from old.pme_id then
      raise exception 'Une inspection planifiée ne peut pas être déplacée vers une autre PME.';
    end if;
    new.created_by := old.created_by;
    new.created_at := old.created_at;
    new.updated_at := now();
    new.updated_by := auth.uid();
    if not exists (
      select 1 from public.staff_profiles s
      where s.user_id = new.inspector_id and s.role in ('admin', 'agent')
    ) then
      raise exception 'L’inspecteur désigné doit avoir un rôle d’agent ou d’administrateur.';
    end if;
  end if;

  if tg_when = 'AFTER' and tg_op = 'UPDATE' then
    insert into public.pme_inspection_appointment_history(
      appointment_id, pme_id, action, before_data, after_data, actor_id
    ) values (
      new.id, new.pme_id, 'MODIFICATION', to_jsonb(old), to_jsonb(new), auth.uid()
    );
  elsif tg_when = 'AFTER' then
    insert into public.pme_inspection_appointment_history(
      appointment_id, pme_id, action, after_data, actor_id
    ) values (new.id, new.pme_id, 'PLANIFICATION', to_jsonb(new), auth.uid());
  end if;
  return new;
end;
$$;
revoke all on function private.audit_pme_inspection_appointment() from public, anon, authenticated;
