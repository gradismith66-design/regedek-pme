create or replace function public.list_inspection_agents()
returns table (user_id uuid, email text, role text)
language sql
stable
security definer
set search_path = ''
as $$
  select s.user_id, u.email::text, s.role
  from public.staff_profiles s
  join auth.users u on u.id = s.user_id
  where s.role in ('admin', 'agent')
    and private.staff_has_permission('inspection.read')
  order by case s.role when 'agent' then 0 else 1 end, lower(u.email)
$$;
revoke all on function public.list_inspection_agents() from public, anon;
grant execute on function public.list_inspection_agents() to authenticated;

