begin;

create table if not exists public.pme_inspection_reports (
  id bigint generated by default as identity primary key,
  pme_id bigint not null references public.pmes(id) on delete cascade,
  result text not null check (result in ('CONFORME','NON_CONFORME','REINSPECTION_REQUISE')),
  observations text not null check (length(trim(observations)) > 0),
  inspection_date date not null default (now() at time zone 'Africa/Kinshasa')::date,
  inspector_id uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists pme_inspection_reports_pme_date_idx on public.pme_inspection_reports(pme_id, inspection_date desc);
create index if not exists pme_inspection_reports_inspector_id_idx on public.pme_inspection_reports(inspector_id);

alter table public.pme_inspection_reports enable row level security;
grant select, insert on public.pme_inspection_reports to authenticated;
grant usage, select on sequence public.pme_inspection_reports_id_seq to authenticated;

drop policy if exists "Staff read inspection reports" on public.pme_inspection_reports;
create policy "Staff read inspection reports" on public.pme_inspection_reports for select to authenticated
  using (exists (select 1 from public.staff_profiles s where s.user_id = (select auth.uid())));
drop policy if exists "Agents report pending inspections" on public.pme_inspection_reports;
create policy "Agents report pending inspections" on public.pme_inspection_reports for insert to authenticated
  with check (
    inspector_id = (select auth.uid())
    and exists (select 1 from public.staff_profiles s where s.user_id = (select auth.uid()) and s.role in ('admin','agent'))
    and exists (select 1 from public.pmes p where p.id = pme_id and p.authorization_status = 'EN_ATTENTE_INSPECTION')
  );

commit;
