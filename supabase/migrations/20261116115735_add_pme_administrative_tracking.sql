create or replace function public.refresh_expired_authorizations()
returns integer language plpgsql security definer set search_path = '' as $$
declare
  changed integer;
begin
  if auth.uid() is null or not exists (
    select 1 from public.staff_profiles s where s.user_id = auth.uid() and s.role = 'admin'
  ) then
    raise exception 'Accès réservé à un administrateur.';
  end if;
  update public.pmes
  set authorization_status = 'EXPIRE',
      authorization_change_reason = 'Expiration automatique à la date de validité.'
  where authorization_status = 'AUTORISE'
    and authorization_expiry_date < current_date;
  get diagnostics changed = row_count;
  return changed;
end;
$$;
revoke all on function public.refresh_expired_authorizations() from public, anon;
grant execute on function public.refresh_expired_authorizations() to authenticated;

