  id bigint generated by default as identity primary key,
  pme_id bigint not null references public.pmes(id) on delete cascade,
  document_name text not null check (length(trim(document_name)) > 0),
  is_required boolean not null default true,
  status text not null default 'MANQUANT' check (status in ('MANQUANT', 'EN_ATTENTE_DE_VERIFICATION', 'VALIDE', 'REJETE')),
  storage_path text unique,
  original_filename text not null default '',
  mime_type text not null default '',
  file_size bigint check (file_size is null or file_size >= 0),
  observations text not null default '',
  rejection_reason text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  reviewed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'REJETE' or length(trim(rejection_reason)) > 0),
  check (status = 'MANQUANT' or storage_path is not null)
);
