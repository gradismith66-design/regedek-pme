create table if not exists public.staff_activity_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  actor_email text not null,
  actor_name text not null,
  actor_role text not null,
  operation text not null check (operation in (
    'pme.created', 'pme.updated', 'pme.archived', 'pme.restored', 'pme.dossier.updated',
    'authorization.updated', 'purchase.created', 'purchase.updated', 'purchase.deleted',
    'document.created', 'document.updated', 'document.deleted', 'inspection.created',
    'staff.invited', 'staff.role.updated', 'staff.permission.updated', 'settings.updated'
  )),
  entity_type text not null check (entity_type in ('pme', 'purchase', 'document', 'inspection', 'staff', 'settings')),
  entity_id text not null,
  pme_id bigint references public.pmes(id) on delete restrict,
  purchase_id bigint references public.achats(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists staff_activity_created_at_idx
  on public.staff_activity_log(created_at desc, id desc);
create index if not exists staff_activity_actor_email_idx
  on public.staff_activity_log(lower(actor_email), created_at desc);
create index if not exists staff_activity_operation_idx
  on public.staff_activity_log(operation, created_at desc);
create index if not exists staff_activity_pme_id_idx
  on public.staff_activity_log(pme_id, created_at desc);

alter table public.staff_activity_log enable row level security;
revoke all on public.staff_activity_log from public, anon, authenticated;
grant select on public.staff_activity_log to authenticated;

drop policy if exists "Super Admin reads staff activity" on public.staff_activity_log;
create policy "Super Admin reads staff activity"
  on public.staff_activity_log for select to authenticated
  using (private.staff_has_permission('activity.read'));

create or replace function private.log_staff_activity(
  p_operation text,
  p_entity_type text,
  p_entity_id text,
  p_pme_id bigint default null,
  p_purchase_id bigint default null,
  p_details jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  actor_email text;
  actor_name text;
  actor_role text;
begin
  if actor is null then
    actor_email := 'system';
    actor_name := 'Système';
    actor_role := 'system';
  else
    select u.email, coalesce(
        nullif(trim(u.raw_user_meta_data ->> 'full_name'), ''),
        nullif(trim(u.raw_user_meta_data ->> 'name'), ''),
        u.email
      ), s.role
    into actor_email, actor_name, actor_role
    from auth.users u
    left join public.staff_profiles s on s.user_id = u.id
    where u.id = actor;
    actor_email := coalesce(actor_email, 'inconnu');
    actor_name := coalesce(actor_name, actor_email);
    actor_role := coalesce(actor_role, 'inconnu');
  end if;

  insert into public.staff_activity_log(
    actor_id, actor_email, actor_name, actor_role, operation, entity_type,
    entity_id, pme_id, purchase_id, details
  ) values (
    actor, actor_email, actor_name, actor_role, p_operation, p_entity_type,
    p_entity_id, p_pme_id, p_purchase_id, coalesce(p_details, '{}'::jsonb)
  );
end;
$$;
revoke all on function private.log_staff_activity(text, text, text, bigint, bigint, jsonb) from public, anon, authenticated;

create or replace function private.audit_pme_activity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  before_row jsonb;
  after_row jsonb;
begin
  if tg_op = 'INSERT' then
    after_row := to_jsonb(new);
    perform private.log_staff_activity('pme.created', 'pme', new.id::text, new.id, null, after_row);
    return new;
  end if;

  before_row := to_jsonb(old);
  after_row := to_jsonb(new);

  if new.archived_at is distinct from old.archived_at then
    perform private.log_staff_activity(
      case when new.archived_at is null then 'pme.restored' else 'pme.archived' end,
      'pme', new.id::text, new.id, null,
      jsonb_build_object('before_archived_at', old.archived_at, 'after_archived_at', new.archived_at)
    );
  end if;

  if (after_row - array[
      'dossier_status', 'dossier_observations', 'dossier_updated_at', 'dossier_updated_by',
      'authorization_status', 'authorization_updated_at', 'authorization_agent_id',
      'authorization_reference', 'authorization_issue_date', 'authorization_expiry_date',
      'authorization_observations', 'non_compliance_reason', 'authorization_change_reason',
      'authority_signer_name', 'authority_signer_title', 'archived_at', 'updated_at'
    ]) is distinct from (before_row - array[
      'dossier_status', 'dossier_observations', 'dossier_updated_at', 'dossier_updated_by',
      'authorization_status', 'authorization_updated_at', 'authorization_agent_id',
      'authorization_reference', 'authorization_issue_date', 'authorization_expiry_date',
      'authorization_observations', 'non_compliance_reason', 'authorization_change_reason',
      'authority_signer_name', 'authority_signer_title', 'archived_at', 'updated_at'
    ]) then
    perform private.log_staff_activity(
      'pme.updated', 'pme', new.id::text, new.id, null,
      jsonb_build_object('before', before_row, 'after', after_row)
    );
  end if;

  if new.dossier_status is distinct from old.dossier_status
     or new.dossier_observations is distinct from old.dossier_observations then
    perform private.log_staff_activity(
      'pme.dossier.updated', 'pme', new.id::text, new.id, null,
      jsonb_build_object(
        'old_status', old.dossier_status, 'new_status', new.dossier_status,
        'observations', new.dossier_observations
      )
    );
  end if;

  if new.authorization_status is distinct from old.authorization_status
     or new.authorization_reference is distinct from old.authorization_reference
     or new.authorization_issue_date is distinct from old.authorization_issue_date
     or new.authorization_expiry_date is distinct from old.authorization_expiry_date
     or new.authorization_observations is distinct from old.authorization_observations
     or new.non_compliance_reason is distinct from old.non_compliance_reason
     or new.authority_signer_name is distinct from old.authority_signer_name
     or new.authority_signer_title is distinct from old.authority_signer_title then
    perform private.log_staff_activity(
      'authorization.updated', 'pme', new.id::text, new.id, null,
      jsonb_build_object('before', before_row, 'after', after_row)
    );
  end if;
  return new;
end;
$$;
revoke all on function private.audit_pme_activity() from public, anon, authenticated;

create or replace function private.audit_purchase_activity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform private.log_staff_activity('purchase.created', 'purchase', new.id::text, new.pme_id, new.id, to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    perform private.log_staff_activity(
      'purchase.updated', 'purchase', new.id::text, new.pme_id, new.id,
      jsonb_build_object('before', to_jsonb(old), 'after', to_jsonb(new))
    );
    return new;
  else
    perform private.log_staff_activity(
      'purchase.deleted', 'purchase', old.id::text, old.pme_id, null,
      jsonb_build_object('deleted_purchase', to_jsonb(old))
    );
    return old;
  end if;
end;
$$;
revoke all on function private.audit_purchase_activity() from public, anon, authenticated;

create or replace function private.audit_document_activity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  pme_key bigint;
  doc_key bigint;
begin
  if tg_op = 'DELETE' then
    pme_key := old.pme_id;
    doc_key := old.id;
  else
    pme_key := new.pme_id;
    doc_key := new.id;
  end if;

  perform private.log_staff_activity(
    case tg_op when 'INSERT' then 'document.created' when 'UPDATE' then 'document.updated' else 'document.deleted' end,
    'document', doc_key::text, pme_key, null,
    jsonb_build_object(
      'before', case when tg_op = 'INSERT' then '{}'::jsonb else to_jsonb(old) end,
      'after', case when tg_op = 'DELETE' then '{}'::jsonb else to_jsonb(new) end
    )
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;
revoke all on function private.audit_document_activity() from public, anon, authenticated;

