create table public.staff_profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('admin', 'agent', 'reader')),
  created_at timestamptz not null default now()
);

create table public.pmes (
  id bigint generated by default as identity primary key,
  nom text not null,
  type text not null default '',
  num_aut text not null default '',
  date_aut date,
  exp_aut date,
  date_agr date,
  exp_agr date,
  contact text not null default '',
  fonction text not null default '',
  tel text not null default '',
  email text not null default '',
  adresse text not null default '',
  communes text not null default '',
  quartiers text not null default '',
  statut_juridique text not null default '',
  source text not null default '',
  nb_autorisations integer not null default 1 check (nb_autorisations > 0),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.achats (
  id bigint generated by default as identity primary key,
  pme_id bigint not null references public.pmes (id) on delete cascade,
  date date not null,
  qte integer not null check (qte > 0),
  detail jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index achats_pme_date_idx on public.achats (pme_id, date desc);
create index pmes_nom_idx on public.pmes using btree (nom);

create table public.settings (
  id boolean primary key default true check (id),
  alerte integer not null default 30 check (alerte >= 0),
  inactif integer not null default 90 check (inactif >= 0),
  updated_at timestamptz not null default now()
);

insert into public.settings (id, alerte, inactif) values (true, 30, 90);

alter table public.staff_profiles enable row level security;
alter table public.pmes enable row level security;
alter table public.achats enable row level security;
alter table public.settings enable row level security;

create policy "Staff can read their own profile"
  on public.staff_profiles for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "Staff can read registry"
  on public.pmes for select to authenticated
  using (exists (
    select 1 from public.staff_profiles s
    where s.user_id = (select auth.uid())
  ));
create policy "Agents can create registry records"
  on public.pmes for insert to authenticated
  with check (exists (
    select 1 from public.staff_profiles s
    where s.user_id = (select auth.uid()) and s.role in ('admin', 'agent')
  ));
create policy "Agents can update registry records"
  on public.pmes for update to authenticated
  using (exists (
    select 1 from public.staff_profiles s
    where s.user_id = (select auth.uid()) and s.role in ('admin', 'agent')
  ))
  with check (exists (
    select 1 from public.staff_profiles s
    where s.user_id = (select auth.uid()) and s.role in ('admin', 'agent')
  ));
create policy "Admins can delete registry records"
  on public.pmes for delete to authenticated
  using (exists (
    select 1 from public.staff_profiles s
    where s.user_id = (select auth.uid()) and s.role = 'admin'
  ));

