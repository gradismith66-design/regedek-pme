create or replace function private.guard_purchase_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'EN_ATTENTE' then
      raise exception 'Un nouvel achat doit rester en attente de validation.';
    end if;
  elsif new.status is distinct from old.status
     and not private.staff_has_permission('purchase.validate') then
    raise exception 'Seul le Super Admin peut valider ou annuler un achat.';
  end if;
  return new;
end;
$$;
revoke all on function private.guard_purchase_status() from public, anon, authenticated;

drop trigger if exists guard_purchase_status on public.achats;
create trigger guard_purchase_status
  before insert or update on public.achats
  for each row execute function private.guard_purchase_status();

create or replace function private.audit_purchase_activity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform private.log_staff_activity('purchase.created', 'purchase', new.id::text, new.pme_id, new.id, to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    if new.status is distinct from old.status then
      perform private.log_staff_activity(
        'purchase.status.updated', 'purchase', new.id::text, new.pme_id, new.id,
        jsonb_build_object('old_status', old.status, 'new_status', new.status)
      );
      if (to_jsonb(new) - 'status') is distinct from (to_jsonb(old) - 'status') then
        perform private.log_staff_activity(
          'purchase.updated', 'purchase', new.id::text, new.pme_id, new.id,
          jsonb_build_object('before', to_jsonb(old), 'after', to_jsonb(new))
        );
      end if;
    else
      perform private.log_staff_activity(
        'purchase.updated', 'purchase', new.id::text, new.pme_id, new.id,
        jsonb_build_object('before', to_jsonb(old), 'after', to_jsonb(new))
      );
    end if;
    return new;
  else
    perform private.log_staff_activity(
      'purchase.deleted', 'purchase', old.id::text, old.pme_id, null,
      jsonb_build_object('deleted_purchase', to_jsonb(old))
    );
    return old;
  end if;
end;
$$;
revoke all on function private.audit_purchase_activity() from public, anon, authenticated;

create table if not exists public.pme_moratoria (
  id bigint generated by default as identity primary key,
  pme_id bigint not null references public.pmes(id) on delete restrict,
  starts_on date not null,
  expires_on date not null,
  duration_days integer generated always as (expires_on - starts_on + 1) stored,
  reason text not null,
  observations text not null default '',
  attachment_path text,
  attachment_name text,
  granted_by uuid references auth.users(id) on delete set null,
  granted_by_name text not null,
  granted_by_email text not null,
  created_at timestamptz not null default now(),
  constraint pme_moratoria_dates_check check (expires_on >= starts_on),
  constraint pme_moratoria_reason_check check (length(trim(reason)) > 0),
  constraint pme_moratoria_attachment_check check (
    (attachment_path is null and attachment_name is null)
    or (attachment_path is not null and attachment_name is not null)
  )
);

