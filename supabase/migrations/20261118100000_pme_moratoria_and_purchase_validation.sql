create or replace function private.audit_pme_moratorium_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_email text;
  actor_name text;
begin
  if actor is null or not private.staff_has_permission('moratorium.manage') then
    raise exception 'Seul le Super Admin peut attribuer un moratoire.';
  end if;
  select u.email, coalesce(
    nullif(trim(u.raw_user_meta_data ->> 'full_name'), ''),
    nullif(trim(u.raw_user_meta_data ->> 'name'), ''),
    u.email
  )
  into actor_email, actor_name
  from auth.users u
  where u.id = actor;

  if actor_email is null then
    raise exception 'Impossible d’identifier l’administrateur qui accorde le moratoire.';
  end if;
  actor_name := coalesce(nullif(trim(actor_name), ''), actor_email);
  if new.attachment_path is not null
     and new.attachment_path not like (new.pme_id::text || '/%') then
    raise exception 'Le chemin du justificatif ne correspond pas à la PME.';
  end if;

  new.granted_by := actor;
  new.granted_by_name := actor_name;
  new.granted_by_email := actor_email;
  new.created_at := now();
  return new;
end;
$$;
revoke all on function private.audit_pme_moratorium_insert() from public, anon, authenticated;

